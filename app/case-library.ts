export function countCaseCharacters(courtCase: CourtCase) {
  return (["prosecution", "defence"] as const)
    .flatMap((side) => courtCase.passages[side].paragraphs)
    .join("")
    .replace(/[\s，。；：「」『』！？、（）《》A-Za-z0-9]/g, "").length;
}
