export type Construct =
  | "factual"
  | "inferential"
  | "semantic"
  | "integration"
  | "evidence";

export type CaseQuestion = {
  id: string;
  construct: Construct;
  prompt: string;
  options: string[];
  answer: number;
  generalCue: string;
  specificCue: string;
  evidence: string;
};

export type CourtCase = {
  id: string;
  caseNumber: string;
  title: string;
  summary: string;
  grade: 1 | 2 | 3 | 4 | 5 | 6;
  difficulty: 1 | 2 | 3 | 4 | 5 | 6;
  episodes: number;
  complexity: string;
  vocabulary: string;
  edbFocus: string;
  passages: {
    prosecution: { label: string; speaker: string; paragraphs: string[] };
    defence: { label: string; speaker: string; paragraphs: string[] };
  };
  questions: CaseQuestion[];
};

function q(
  caseId: string,
  index: number,
  construct: Construct,
  prompt: string,
  options: string[],
  answer: number,
  hint: string,
  evidence: string,
): CaseQuestion {
  return {
    id: `${caseId}-q${index}`,
    construct,
    prompt,
    options,
    answer,
    generalCue: hint,
    specificCue: `在陳詞中找出這句：「${evidence}」`,
    evidence,
  };
}

